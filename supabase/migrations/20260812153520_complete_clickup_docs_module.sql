create or replace function private.has_document_role(
  target_document_id uuid,
  allowed_roles text[]
)
returns boolean
language sql
stable
security definer
set search_path = ''
set row_security = off
as $$
  select exists (
    select 1
    from public.document_collaborators dc
    where dc.document_id = target_document_id
      and dc.user_id = (select auth.uid())
      and dc.role = any(allowed_roles)
  );
$$;

create or replace function private.can_view_document(target_document_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
set row_security = off
as $$
  select exists (
    select 1
    from public.documents d
    where d.id = target_document_id
      and (
        d.is_published
        or d.user_id = (select auth.uid())
        or private.is_workspace_member(d.workspace_id)
        or private.has_document_role(d.id, array['owner','editor','commenter','viewer'])
      )
  );
$$;

create or replace function private.can_edit_document(target_document_id uuid)
