create or replace function private.capture_document_version()
returns trigger
language plpgsql
security definer
set search_path = ''
set row_security = off
as $$
begin
  if (
    old.title is distinct from new.title
    or old.icon is distinct from new.icon
    or old.cover_url is distinct from new.cover_url
    or old.content is distinct from new.content
  ) and not exists (
    select 1 from public.document_versions dv
    where dv.document_id = old.id
      and dv.created_by is not distinct from (select auth.uid())
      and dv.created_at > now() - interval '5 minutes'
  ) then
    insert into public.document_versions (
      document_id, title, icon, cover_url, content, change_summary, created_by
    ) values (
      old.id, old.title, old.icon, old.cover_url,
      coalesce(old.content, '{"type":"doc","content":[]}'::jsonb),
      'Autosaved revision', (select auth.uid())
    );
  end if;

  new.updated_at := now();
  return new;
end;
$$;

revoke all on function private.capture_document_version() from public, anon, authenticated;
drop trigger if exists documents_capture_version on public.documents;
create trigger documents_capture_version before update on public.documents
for each row execute function private.capture_document_version();

