type TranslationContextValue = {
   t: (key: string, ...args: unknown[]) => string;
   locale: string;
   setLocale: (locale: string) => void;
};

const TranslationContext = createContext<TranslationContextValue>({
   t: (key: string) => key,
   locale: 'en',
   setLocale: () => {},
});

export function useTranslation() {
   return useContext(TranslationContext);
}

export function TranslationProvider({ children }: { children: React.ReactNode }) {
   const [locale, setLocaleState] = React.useState<string>(() => {
     if (typeof window !== 'undefined') {
       return localStorage.getItem('avaxa_locale') || 'en';
     }
     return 'en';
   });

   const setLocale = useCallback((newLocale: string) => {
     setLocaleState(newLocale);
     if (typeof window !== 'undefined') {
       localStorage.setItem('avaxa_locale', newLocale);
     }
   }, []);

   const t = useCallback((key: string, ...args: unknown[]) => {
     const dict = locale === 'vi' ? vi : en;
     let value = dict[key];
     if (value === undefined) {
       value = en[key]; // fallback to en
     }
     if (typeof value === 'function') {
       value = value(...args as string[]);
     }
     if (value === undefined) {
       return key;
     }
     return String(value);
   }, [locale]);

  return (
    <TranslationContext.Provider value={{ t, locale, setLocale }}>
      {children}
    </TranslationContext.Provider>
  );
}

export { en, vi };
